def section_tests(section_key: str) -> tuple[Test, ...]:
    return tuple(t for t in TESTS if t.section == section_key)


def by_id(question_id: int) -> Question | None:
    return QUESTION_BY_ID.get(int(question_id))


def by_test(test_key: str) -> Test | None:
    return TEST_BY_KEY.get(test_key)


def pick_questions(test_key: str, rng=None) -> list[Question]:
    """Вопросы теста в случайном порядке."""
    import random

    rng = rng or random
    test = TEST_BY_KEY.get(test_key)
    if test is None:
        return []
    picked = [q for q in (by_id(qid) for qid in test.question_ids) if q is not None]
    rng.shuffle(picked)
    return picked


