def _lesson_of(scenario) -> int:
    """Какому занятию относится сценарий: 2 — ОДН/комы, 3 — ОКС/шоки."""
    if isinstance(scenario, str):
        scenario = next((sc["num"] for sc in SCENARIOS if sc["key"] == scenario), 3)
    return _SCENARIO_LESSON.get(int(scenario), 3)


def _norm_groups(keys) -> tuple[tuple[str, ...], ...]:
    """Привести ключи к виду «кортеж групп, в каждой — синонимы».

    В вопросах преподавателя часть групп задана вложенно (две группы как одна),
    поэтому лишнюю вложенность раскрываем: ((a, b), (c, d)) → (a, b), (c, d).
    """
    out: list[tuple[str, ...]] = []
    for group in keys or ():
        if group and isinstance(group[0], tuple):
            out.extend(tuple(item) for item in group)
        else:
            out.append(tuple(group))
    return tuple(out)


def _q(qid, test, section, scenario, ru, en, ref_ru, ref_en, keys, exp_ru, exp_en,
       checklist, must_not=(), criteria=()) -> Question:
    return Question(id=qid, test=test, section=section, scenario=scenario,
                    lesson=_lesson_of(scenario),
                    text={"ru": ru, "en": en},
                    reference={"ru": ref_ru, "en": ref_en},
                    keys=_norm_groups(keys),
                    explain={"ru": exp_ru, "en": exp_en},
                    checklist=checklist, must_not=tuple(must_not),
                    criteria=tuple(criteria))


