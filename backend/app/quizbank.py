@dataclass(frozen=True)
class Question:
    id: int
    test: str                 # ключ теста внутри раздела
    section: str              # diagnostics | treatment
    scenario: int             # номер сценария станции 1–9
    text: dict[str, str]
    reference: dict[str, str]  # эталонный ответ
    keys: tuple[tuple[str, ...], ...]   # группы синонимов
    explain: dict[str, str]
    checklist: str
    must_not: tuple[str, ...] = ()
    clip: str = ""            # видео пока нет: окно пустое, клип вставим позже
    lesson: int = 3           # занятие из таблиц: 2 — ОДН/комы, 3 — ОКС/шоки
    # критерии оценивания из чек-листа: (название, данные, [(группа синонимов), ...])
    # ответ проверяется по всем критериям сразу — это «ИИ оценивает по 2–5 критериям»
    criteria: tuple = ()

    def public(self, lang: str = "ru") -> dict:
        lang = lang if lang in LANGS else "ru"
        return {
            "id": self.id,
            "test": self.test,
            "section": self.section,
            "scenario": self.scenario,
            "lesson": self.lesson,
            "text": self.text[lang],
            "clip": self.clip,
        }


# ------------------------------- разделы и тесты -------------------------------
@dataclass(frozen=True)
class Test:
    key: str
    section: str
    title: dict[str, str]
    question_ids: tuple[int, ...] = ()
    lesson: int = 3           # занятие из таблиц: 2 — ОДН/комы, 3 — ОКС/шоки, 4 — зачёт

    def public(self, lang: str = "ru", count: int | None = None) -> dict:
        lang = lang if lang in LANGS else "ru"
        size = len(self.question_ids) if count is None else count
        return {"key": self.key, "section": self.section, "lesson": self.lesson,
                "title": self.title[lang], "count": size}


@dataclass(frozen=True)
class Section:
    key: str
    title: dict[str, str]
    description: dict[str, str]

    def public(self, lang: str = "ru") -> dict:
        lang = lang if lang in LANGS else "ru"
        return {"key": self.key, "title": self.title[lang],
                "description": self.description[lang]}


