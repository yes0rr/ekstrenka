# ------------------------------- тесты -------------------------------
def _build_tests() -> tuple[Test, ...]:
    built: list[Test] = []
    for section in SECTIONS:
        for sc in SCENARIOS:
            key = f"{'diag' if section.key == 'diagnostics' else 'treat'}_{sc['key']}"
            ids = tuple(q.id for q in QUESTIONS if q.test == key)
            if not ids:
                continue
            built.append(Test(key=key, section=section.key,
                              title={"ru": sc["ru"], "en": sc["en"]}, question_ids=ids))
        all_ids = tuple(q.id for q in QUESTIONS if q.section == section.key)
        built.append(Test(key=f"{section.key}_all", section=section.key,
                          title={"ru": "Все вопросы раздела", "en": "All questions of the section"},
                          question_ids=all_ids))
    return tuple(built)


TESTS: tuple[Test, ...] = _build_tests()
TEST_BY_KEY = {t.key: t for t in TESTS}
TOTAL = len(QUESTIONS)
RUN_SIZE = len(TESTS[0].question_ids) if TESTS else 0


def section_tests(section_key: str) -> tuple[Test, ...]:
    return tuple(t for t in TESTS if t.section == section_key)


def by_id(question_id: int) -> Question | None:
    return QUESTION_BY_ID.get(int(question_id))


def by_test(test_key: str) -> Test | None:
    return TEST_BY_KEY.get(test_key)


def pick_questions(test_key: str, rng=None) -> list[Question]:
    """Вопросы теста в случайном порядке."""
    import random

    rng = rng or random
    test = TEST_BY_KEY.get(test_key)
    if test is None:
        return []
    picked = [q for q in (by_id(qid) for qid in test.question_ids) if q is not None]
    rng.shuffle(picked)
    return picked


