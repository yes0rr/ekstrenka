def _lesson_title(num: int, base: str) -> dict[str, str]:
    """«Занятие 3 · ОКС и шоки: ОКС 1, кардиогенный шок» — чтобы было видно, к какому занятию тест."""
    lesson = next((l for l in LESSONS if l["num"] == num), None)
    ru = f"{lesson['ru']}: {base}" if lesson else base
    en = f"{lesson['en']}: {base}" if lesson else base
    return {"ru": ru, "en": en}


def _build_tests() -> tuple[Test, ...]:
    built: list[Test] = []
    for section in SECTIONS:
        prefix = "diag" if section.key == "diagnostics" else "treat"
        # сначала занятия: 2 — ОДН/комы, 3 — ОКС/шоки (как в таблицах преподавателя)
        for lesson in (2, 3):
            for sc in SCENARIOS:
                if _lesson_of(sc["key"]) != lesson:
                    continue
                key = f"{prefix}_{sc['key']}"
                ids = tuple(q.id for q in QUESTIONS if q.test == key)
                if not ids:
                    continue
                built.append(Test(key=key, section=section.key, lesson=lesson,
                                  title=_lesson_title(lesson, sc["ru"]), question_ids=ids))
            lesson_ids = tuple(q.id for q in QUESTIONS
                               if q.section == section.key and q.lesson == lesson)
            built.append(Test(key=f"{prefix}_lesson{lesson}", section=section.key, lesson=lesson,
                              title={"ru": f"{LESSONS[lesson - 1]['ru']}: все сценарии занятия",
                                     "en": f"{LESSONS[lesson - 1]['en']}: all scenarios of the lesson"},
                              question_ids=lesson_ids))
        all_ids = tuple(q.id for q in QUESTIONS if q.section == section.key)
        built.append(Test(key=f"{section.key}_all", section=section.key, lesson=4,
                          title={"ru": "Занятие 4 · Зачёт по всем темам",
                                 "en": "Lesson 4 · Final test: all topics"},
                          question_ids=all_ids))
    return tuple(built)


TESTS: tuple[Test, ...] = _build_tests()
